import type { EdgeFin, FanFin, Finlets, Pt, TailFin } from './geometry';

/** 体の上に足す部品（ひげ・吻・触角・脚など） */
export interface Extra {
  d: string;
  /** 塗り: fin=ひれの色 / body=背の色 / belly=腹の色 / edge=輪郭の色 / glow=光 / dark=墨 / none=線だけ */
  paint: 'fin' | 'body' | 'belly' | 'edge' | 'glow' | 'dark' | 'none';
  /** 線の太さ（輪郭の何倍か。0 で線なし） */
  w?: number;
  /** under=体の下に描く（体から生える物）/ over=体の上 */
  layer?: 'under' | 'over';
}

export interface FormSpec {
  top: string;
  bottom: string;
  eye?: [number, number, number];
  /** 2つめの目（ヒラメ・カレイ） */
  eye2?: [number, number, number];
  mouth?: string;
  gill?: string[];
  lateral?: string;
  dorsal?: EdgeFin[];
  anal?: EdgeFin[];
  pectoral?: FanFin;
  pelvic?: FanFin;
  caudal?: TailFin;
  finletsTop?: Finlets;
  finletsBot?: Finlets;
  /** 脂びれ（サケ・アユ）: 背の線の上 x の位置に小さな丸いひれ */
  adipose?: { x: number; w: number; h: number };
  keel?: Pt;
  extras?: Extra[];
  /** うろこの大きさ（0 で描かない） */
  scale?: number;
}

