// 辞書キーの最大長（最長一致のスキャン上限）
const MAX_KEY_LEN = Object.keys(READINGS).reduce((m, k) => Math.max(m, k.length), 1);

export interface RubySeg {
  t: string;   // 表示テキスト
  r?: string;  // ルビ（読み）。無ければプレーン表示
}

/**
 * 文字列を「読み付き／プレーン」のセグメント列に分解する（左から最長一致）。
 * 辞書にある語にだけ読みを当て、無い部分はそのまま返す（誤った読みを出さない）。
 */
export function toRubySegments(text: string): RubySeg[] {
  const segs: RubySeg[] = [];
  let plain = '';
  let i = 0;
  const flush = () => { if (plain) { segs.push({ t: plain }); plain = ''; } };

  while (i < text.length) {
    let matched: string | null = null;
    const maxLen = Math.min(MAX_KEY_LEN, text.length - i);
    for (let len = maxLen; len >= 1; len--) {
      const sub = text.slice(i, i + len);
      if (READINGS[sub] !== undefined) { matched = sub; break; }
    }
    if (matched) {
      flush();
      segs.push({ t: matched, r: READINGS[matched] });
      i += matched.length;
    } else {
      plain += text[i];
      i += 1;
    }
  }
  flush();
  return segs;
}
